# === block: score_0 (check id='phase_classification') ===
def score_0(artifact, step, ctx):
    config = step.get('config', {})
    disordered_z = set(config.get('disordered_z', []))
    critical_z = set(config.get('critical_z', []))
    ordered_z = set(config.get('ordered_z', []))
    th_dis = config.get('disordered_threshold', 1.5)
    th_crit_up = config.get('critical_upper_threshold', 0.7)
    th_ord_up = config.get('ordered_upper_threshold', 0.15)

    data = {}
    for row in artifact:
        z = float(row['z'])
        L = int(row['L'])
        try:
            a = float(row['A_z'])
        except (ValueError, KeyError):
            return 0.0
        if z not in data:
            data[z] = {}
        data[z][L] = a

    zs = sorted(data.keys())
    if not zs:
        return 0.0

    correct = 0
    total = len(disordered_z) + len(critical_z) + len(ordered_z)
    for z in data:
        if z not in disordered_z | critical_z | ordered_z:
            continue
        if 90 not in data[z] or 120 not in data[z]:
            continue
        a90 = data[z][90]
        a120 = data[z][120]
        if a90 <= 0 or a120 <= 0:
            continue
        try:
            log_ratio = math.log(a120 / a90)
            log_L = math.log(120.0 / 90.0)
            eta = 2.0 - log_ratio / log_L
        except (ValueError, ZeroDivisionError):
            continue
        if z in disordered_z:
            if eta >= th_dis:
                correct += 1
        elif z in critical_z:
            if 0 < eta < th_crit_up:
                correct += 1
        else:  # ordered
            if abs(eta) <= th_ord_up:
                correct += 1

    score = correct / total if total > 0 else 0.0
    return score


_SCORERS = {
    'phase_classification': score_0,
}


def _step_id(step, index):
    sid = str(step.get("id", "")).strip()
    if sid:
        return sid
    output = str(step.get("output_file", "")).split("/")[-1].rsplit(".", 1)[0]
    kind = str(step.get("kind") or step.get("metric") or "score").strip()
    base = "_".join(part for part in (output, kind) if part).strip("_")
    return base or ("check_" + str(index))


def main():
    _ff_contract_gate()
    with open("/tests/grading_spec.json") as f:
        spec = json.load(f)
    outputs_dir = "/app/outputs"
    ctx = prepare(outputs_dir, spec)
    steps = spec.get("steps", spec.get("checks", [])) or []
    breakdown = {}
    total = 0.0
    for index, step in enumerate(steps):
        sid = _step_id(step, index)
        output_file = str(step.get("output_file", "")).split("/")[-1]
        weight = float(step.get("weight", 0.0))
        artifact = load_artifact(os.path.join(outputs_dir, output_file)) if output_file else None
        fn = _SCORERS.get(sid)
        if fn is None:
            score = 0.0
        else:
            try:
                score = float(fn(artifact, step, ctx))
            except Exception as exc:  # noqa: BLE001
                score = 0.0
                breakdown.setdefault("_errors", {})[sid] = repr(exc)
        score = max(0.0, min(1.0, score))
        breakdown[sid or output_file] = {"score": score, "weight": weight}
        total += score * weight
    os.makedirs("/logs/verifier", exist_ok=True)
    with open("/logs/verifier/reward.txt", "w") as f:
        f.write(str(round(total, 6)))
    with open("/logs/verifier/breakdown.json", "w") as f:
        json.dump(breakdown, f, indent=2)


if __name__ == "__main__":
    main()
