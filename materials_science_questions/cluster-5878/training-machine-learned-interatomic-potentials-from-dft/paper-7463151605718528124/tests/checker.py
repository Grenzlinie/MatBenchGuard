# === block: score_0 (check id='step_refinement_results') ===
def score_0(artifact, step, ctx):
    valid_rows = 0
    sum_delta_rmsd = 0.0
    sum_delta_gdt = 0.0
    num_improved_rmsd = 0
    for row in artifact:
        try:
            init_r = float(row['initial_RMSD'])
            final_r = float(row['final_RMSD'])
            init_g = float(row['initial_GDT_HA'])
            final_g = float(row['final_GDT_HA'])
        except (ValueError, KeyError):
            continue
        delta_r = final_r - init_r
        delta_g = final_g - init_g
        valid_rows += 1
        sum_delta_rmsd += delta_r
        sum_delta_gdt += delta_g
        if delta_r < 0:
            num_improved_rmsd += 1
    if valid_rows == 0:
        return 0.0
    avg_delta_rmsd = sum_delta_rmsd / valid_rows
    avg_delta_gdt = sum_delta_gdt / valid_rows
    frac_improved = num_improved_rmsd / valid_rows
    # Row count score: full credit if >= min_rows, else proportional
    row_score = min(1.0, valid_rows / step['min_rows']) * 0.2
    # RMSD improvement: reward negative delta; -0.01 or better earns full credit
    rmsd_score = 0.3 * max(0.0, min(1.0, (-avg_delta_rmsd) / 0.01))
    # GDT-HA improvement: reward positive delta; 0.005 or better earns full credit
    gdt_score = 0.3 * max(0.0, min(1.0, avg_delta_gdt / 0.005))
    # Fraction improved: 50% or more earns full credit
    frac_score = 0.2 * min(1.0, frac_improved / step['fraction_improved_rmsd_threshold'])
    return row_score + rmsd_score + gdt_score + frac_score


_SCORERS = {
    'step_refinement_results': score_0,
}


def _step_id(step, index):
    sid = str(step.get("id", "")).strip()
    if sid:
        return sid
    output = str(step.get("output_file", "")).split("/")[-1].rsplit(".", 1)[0]
    kind = str(step.get("kind") or step.get("metric") or "score").strip()
    base = "_".join(part for part in (output, kind) if part).strip("_")
    return base or ("check_" + str(index))


def main():
    _ff_contract_gate()
    with open("/tests/grading_spec.json") as f:
        spec = json.load(f)
    outputs_dir = "/app/outputs"
    ctx = prepare(outputs_dir, spec)
    steps = spec.get("steps", spec.get("checks", [])) or []
    breakdown = {}
    total = 0.0
    for index, step in enumerate(steps):
        sid = _step_id(step, index)
        output_file = str(step.get("output_file", "")).split("/")[-1]
        weight = float(step.get("weight", 0.0))
        artifact = load_artifact(os.path.join(outputs_dir, output_file)) if output_file else None
        fn = _SCORERS.get(sid)
        if fn is None:
            score = 0.0
        else:
            try:
                score = float(fn(artifact, step, ctx))
            except Exception as exc:  # noqa: BLE001
                score = 0.0
                breakdown.setdefault("_errors", {})[sid] = repr(exc)
        score = max(0.0, min(1.0, score))
        breakdown[sid or output_file] = {"score": score, "weight": weight}
        total += score * weight
    os.makedirs("/logs/verifier", exist_ok=True)
    with open("/logs/verifier/reward.txt", "w") as f:
        f.write(str(round(total, 6)))
    with open("/logs/verifier/breakdown.json", "w") as f:
        json.dump(breakdown, f, indent=2)


if __name__ == "__main__":
    main()
