# === block: score_0 (check id='step_final_results') ===
def score_0(artifact, step, ctx):
    freq = float(artifact['resonant_frequency_hz'])
    disp = float(artifact['maximum_displacement_um'])
    cap_val = float(artifact['capacitance_pF'])
    temp_prof = artifact['temperature_profile']
    expected_zs = [0, 25, 50, 75, 100]
    agent_temps = []
    for z in expected_zs:
        found = False
        for entry in temp_prof:
            if int(entry['z_mm']) == z:
                agent_temps.append(float(entry['temperature_C']))
                found = True
                break
        if not found:
            agent_temps.append(None)
    temp_score = 0.0
    if None not in agent_temps:
        gold_temps = step['gold_temperature_points_C']
        errors = [abs(a - g) for a, g in zip(agent_temps, gold_temps)]
        mae = sum(errors) / len(errors)
        temp_score = max(0.0, 1.0 - mae / step['max_mae_C'])
    gold_freq = step['gold_frequency_hz']
    freq_score = max(0.0, 1.0 - abs(freq - gold_freq) / step['tolerance_frequency_hz'])
    gold_disp = step['gold_displacement_um']
    disp_score = max(0.0, 1.0 - abs(disp - gold_disp) / step['tolerance_displacement_um'])
    gold_cap = step['gold_capacitance_pF']
    cap_score = max(0.0, 1.0 - abs(cap_val - gold_cap) / step['tolerance_capacitance_pF'])
    wf = step['weight_frequency']
    wd = step['weight_displacement']
    wc = step['weight_capacitance']
    wt = step['weight_temperature']
    total = freq_score * wf + disp_score * wd + cap_score * wc + temp_score * wt
    return total


_SCORERS = {
    'step_final_results': score_0,
}


def _step_id(step, index):
    sid = str(step.get("id", "")).strip()
    if sid:
        return sid
    output = str(step.get("output_file", "")).split("/")[-1].rsplit(".", 1)[0]
    kind = str(step.get("kind") or step.get("metric") or "score").strip()
    base = "_".join(part for part in (output, kind) if part).strip("_")
    return base or ("check_" + str(index))


def main():
    _ff_contract_gate()
    with open("/tests/grading_spec.json") as f:
        spec = json.load(f)
    outputs_dir = "/app/outputs"
    ctx = prepare(outputs_dir, spec)
    steps = spec.get("steps", spec.get("checks", [])) or []
    breakdown = {}
    total = 0.0
    for index, step in enumerate(steps):
        sid = _step_id(step, index)
        output_file = str(step.get("output_file", "")).split("/")[-1]
        weight = float(step.get("weight", 0.0))
        artifact = load_artifact(os.path.join(outputs_dir, output_file)) if output_file else None
        fn = _SCORERS.get(sid)
        if fn is None:
            score = 0.0
        else:
            try:
                score = float(fn(artifact, step, ctx))
            except Exception as exc:  # noqa: BLE001
                score = 0.0
                breakdown.setdefault("_errors", {})[sid] = repr(exc)
        score = max(0.0, min(1.0, score))
        breakdown[sid or output_file] = {"score": score, "weight": weight}
        total += score * weight
    os.makedirs("/logs/verifier", exist_ok=True)
    with open("/logs/verifier/reward.txt", "w") as f:
        f.write(str(round(total, 6)))
    with open("/logs/verifier/breakdown.json", "w") as f:
        json.dump(breakdown, f, indent=2)


if __name__ == "__main__":
    main()
