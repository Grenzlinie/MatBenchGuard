# === block: score_0 (check id='scattering_rates_check') ===
def score_0(artifact, step, ctx):
    gold_rows = step.get("gold_rows", [])
    rate_tol = step.get("rate_tolerance", 0.20)
    ratio_tol = step.get("ratio_tolerance", 0.10)
    if not gold_rows:
        return 1.0
    agent_rows = artifact if isinstance(artifact, list) else []

    def float_or_none(v):
        try:
            return float(v)
        except (ValueError, TypeError):
            return None

    def make_key(row):
        L_val = float_or_none(row.get("L"))
        x_val = float_or_none(row.get("x"))
        trans = str(row.get("transition", "")).strip()
        if L_val is None or x_val is None:
            return None
        return (round(L_val, 4), round(x_val, 4), trans)

    agent_map = {}
    for row in agent_rows:
        key = make_key(row)
        if key is None:
            continue
        agent_map[key] = row

    num_total = len(gold_rows)
    num_ok = 0
    for g in gold_rows:
        gk = make_key(g)
        if gk is None or gk not in agent_map:
            continue
        a = agent_map[gk]
        try:
            w_np = float(a["W_np"])
            w_p = float(a["W_p"])
            ratio = float(a["ratio"])
        except (KeyError, ValueError):
            continue
        g_np = g["W_np"]
        g_p = g["W_p"]
        g_ratio = g["ratio"]
        if g_np == 0.0 or g_p == 0.0 or g_ratio == 0.0:
            continue
        rel_np = abs(w_np - g_np) / abs(g_np)
        rel_p = abs(w_p - g_p) / abs(g_p)
        rel_r = abs(ratio - g_ratio) / abs(g_ratio)
        if rel_np <= rate_tol and rel_p <= rate_tol and rel_r <= ratio_tol:
            num_ok += 1
    score = num_ok / num_total if num_total > 0 else 0.0
    return score


_SCORERS = {
    'scattering_rates_check': score_0,
}


def _step_id(step, index):
    sid = str(step.get("id", "")).strip()
    if sid:
        return sid
    output = str(step.get("output_file", "")).split("/")[-1].rsplit(".", 1)[0]
    kind = str(step.get("kind") or step.get("metric") or "score").strip()
    base = "_".join(part for part in (output, kind) if part).strip("_")
    return base or ("check_" + str(index))


def main():
    _ff_contract_gate()
    with open("/tests/grading_spec.json") as f:
        spec = json.load(f)
    outputs_dir = "/app/outputs"
    ctx = prepare(outputs_dir, spec)
    steps = spec.get("steps", spec.get("checks", [])) or []
    breakdown = {}
    total = 0.0
    for index, step in enumerate(steps):
        sid = _step_id(step, index)
        output_file = str(step.get("output_file", "")).split("/")[-1]
        weight = float(step.get("weight", 0.0))
        artifact = load_artifact(os.path.join(outputs_dir, output_file)) if output_file else None
        fn = _SCORERS.get(sid)
        if fn is None:
            score = 0.0
        else:
            try:
                score = float(fn(artifact, step, ctx))
            except Exception as exc:  # noqa: BLE001
                score = 0.0
                breakdown.setdefault("_errors", {})[sid] = repr(exc)
        score = max(0.0, min(1.0, score))
        breakdown[sid or output_file] = {"score": score, "weight": weight}
        total += score * weight
    os.makedirs("/logs/verifier", exist_ok=True)
    with open("/logs/verifier/reward.txt", "w") as f:
        f.write(str(round(total, 6)))
    with open("/logs/verifier/breakdown.json", "w") as f:
        json.dump(breakdown, f, indent=2)


if __name__ == "__main__":
    main()
