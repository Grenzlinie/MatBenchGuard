# === block: score_0 (check id='step04_extract_alpha_case_depths') ===
def score_0(artifact, step, ctx):
        # Parse CSV, keyed by stress (rounded to nearest int to avoid float mismatches)
        depths = {}
        for row in artifact:
            try:
                s = float(row.get("stress_MPa"))
                d = float(row.get("max_depth_um"))
                depths[int(round(s))] = d
            except (ValueError, TypeError):
                continue
        # Extract parameters from step config
        target_605 = step.get("depth_target_at_605_MPa_um", 16.0)
        target_615 = step.get("depth_target_at_615_MPa_um", 45.0)
        tol = step.get("depth_tolerance_um", 5.0)
        low_stress = int(step.get("jump_stress_low_MPa", 611.0))
        high_stress = int(step.get("jump_stress_high_MPa", 612.0))
        ratio_min = step.get("jump_ratio_min", 2.0)

        def depth_score(observed, target, tol):
            """Tolerance band: 1.0 if |obs - target| <= tol; 0.5 if <= 2*tol; else 0.0."""
            delta = abs(observed - target)
            if delta <= tol:
                return 1.0
            elif delta <= 2 * tol:
                return 0.5
            return 0.0

        score_605 = depth_score(depths.get(605, 9999), target_605, tol)
        score_615 = depth_score(depths.get(615, 9999), target_615, tol)

        # Jump ratio
        depth_low = depths.get(low_stress, 0.0)
        depth_high = depths.get(high_stress, 0.0)
        if depth_low > 1e-6 and (depth_high / depth_low) >= ratio_min:
            jump_score = 1.0
        else:
            jump_score = 0.0

        # Weighted combination
        return 0.3 * score_605 + 0.3 * score_615 + 0.4 * jump_score


_SCORERS = {
    'step04_extract_alpha_case_depths': score_0,
}


def _step_id(step, index):
    sid = str(step.get("id", "")).strip()
    if sid:
        return sid
    output = str(step.get("output_file", "")).split("/")[-1].rsplit(".", 1)[0]
    kind = str(step.get("kind") or step.get("metric") or "score").strip()
    base = "_".join(part for part in (output, kind) if part).strip("_")
    return base or ("check_" + str(index))


def main():
    _ff_contract_gate()
    with open("/tests/grading_spec.json") as f:
        spec = json.load(f)
    outputs_dir = "/app/outputs"
    ctx = prepare(outputs_dir, spec)
    steps = spec.get("steps", spec.get("checks", [])) or []
    breakdown = {}
    total = 0.0
    for index, step in enumerate(steps):
        sid = _step_id(step, index)
        output_file = str(step.get("output_file", "")).split("/")[-1]
        weight = float(step.get("weight", 0.0))
        artifact = load_artifact(os.path.join(outputs_dir, output_file)) if output_file else None
        fn = _SCORERS.get(sid)
        if fn is None:
            score = 0.0
        else:
            try:
                score = float(fn(artifact, step, ctx))
            except Exception as exc:  # noqa: BLE001
                score = 0.0
                breakdown.setdefault("_errors", {})[sid] = repr(exc)
        score = max(0.0, min(1.0, score))
        breakdown[sid or output_file] = {"score": score, "weight": weight}
        total += score * weight
    os.makedirs("/logs/verifier", exist_ok=True)
    with open("/logs/verifier/reward.txt", "w") as f:
        f.write(str(round(total, 6)))
    with open("/logs/verifier/breakdown.json", "w") as f:
        json.dump(breakdown, f, indent=2)


if __name__ == "__main__":
    main()
