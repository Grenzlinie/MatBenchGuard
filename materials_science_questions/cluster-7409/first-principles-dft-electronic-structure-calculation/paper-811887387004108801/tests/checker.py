# === block: score_0 (check id='s3_vde_gap') ===
def score_0(artifact, step, ctx):
    sc = artifact.get("ScSi16-", {})
    lu = artifact.get("LuSi16-", {})

    def get_float(d, key):
        v = d.get(key, None)
        if v is None:
            raise KeyError(f"Missing {key}")
        return float(v)

    try:
        Ea_Sc = get_float(sc, "E_anion_Ha")
        En_Sc = get_float(sc, "E_neutral_Ha")
        Ea_Lu = get_float(lu, "E_anion_Ha")
        En_Lu = get_float(lu, "E_neutral_Ha")
        gap_Sc = get_float(sc, "HOMO_LUMO_gap_eV")
        gap_Lu = get_float(lu, "HOMO_LUMO_gap_eV")
    except (KeyError, TypeError, ValueError):
        return 0.0

    eV_per_Ha = 27.2114
    vde_Sc = (En_Sc - Ea_Sc) * eV_per_Ha
    vde_Lu = (En_Lu - Ea_Lu) * eV_per_Ha

    gold = step.get("gold_vde_eV", 4.25)
    tol = step.get("vde_tolerance_eV", 0.15)

    score_vde = 0.0
    for vde in (vde_Sc, vde_Lu):
        diff = abs(vde - gold)
        if diff <= tol:
            score_vde += 0.4
        else:
            max_diff = 3 * tol
            if diff <= max_diff:
                score_vde += 0.4 * (1.0 - (diff - tol) / (max_diff - tol))

    gap_thresh = step.get("gap_threshold_eV", 1.5)
    consistency_tol = step.get("gap_consistency_tol_eV", 1.0)
    score_gap = 0.0
    if gap_Sc >= gap_thresh and gap_Lu >= gap_thresh:
        score_gap += 0.1
    if abs(gap_Sc - gap_Lu) <= consistency_tol:
        score_gap += 0.1

    return min(1.0, max(0.0, score_vde + score_gap))


_SCORERS = {
    's3_vde_gap': score_0,
}


def _step_id(step, index):
    sid = str(step.get("id", "")).strip()
    if sid:
        return sid
    output = str(step.get("output_file", "")).split("/")[-1].rsplit(".", 1)[0]
    kind = str(step.get("kind") or step.get("metric") or "score").strip()
    base = "_".join(part for part in (output, kind) if part).strip("_")
    return base or ("check_" + str(index))


def main():
    _ff_contract_gate()
    with open("/tests/grading_spec.json") as f:
        spec = json.load(f)
    outputs_dir = "/app/outputs"
    ctx = prepare(outputs_dir, spec)
    steps = spec.get("steps", spec.get("checks", [])) or []
    breakdown = {}
    total = 0.0
    for index, step in enumerate(steps):
        sid = _step_id(step, index)
        output_file = str(step.get("output_file", "")).split("/")[-1]
        weight = float(step.get("weight", 0.0))
        artifact = load_artifact(os.path.join(outputs_dir, output_file)) if output_file else None
        fn = _SCORERS.get(sid)
        if fn is None:
            score = 0.0
        else:
            try:
                score = float(fn(artifact, step, ctx))
            except Exception as exc:  # noqa: BLE001
                score = 0.0
                breakdown.setdefault("_errors", {})[sid] = repr(exc)
        score = max(0.0, min(1.0, score))
        breakdown[sid or output_file] = {"score": score, "weight": weight}
        total += score * weight
    os.makedirs("/logs/verifier", exist_ok=True)
    with open("/logs/verifier/reward.txt", "w") as f:
        f.write(str(round(total, 6)))
    with open("/logs/verifier/breakdown.json", "w") as f:
        json.dump(breakdown, f, indent=2)


if __name__ == "__main__":
    main()
