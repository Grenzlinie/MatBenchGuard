# === block: score_0 (check id='phase_diagram') ===
def score_0(artifact, step, ctx):
    import csv

    artifact = artifact  # passed by harness
    step = step

    if not artifact or not isinstance(artifact, list):
        return 0.0

    check_points = step.get('check_points', [])
    if not check_points:
        return 0.0

    matched = 0
    for cp in check_points:
        target_r = cp['r']
        allowed = set(cp['allowed'])
        # find rows with r within ±0.05
        candidates = []
        for row in artifact:
            try:
                r_val = float(row.get('r', None))
            except (ValueError, TypeError):
                continue
            if abs(r_val - target_r) <= 0.05:
                candidates.append(row.get('domain_type', '').strip())
        if not candidates:
            # no data near this point; treat as miss
            continue
        # if any candidate is in allowed set, count as match
        if any(c in allowed for c in candidates):
            matched += 1

    score = matched / len(check_points) if check_points else 0.0
    return score


# === block: score_1 (check id='transition_points') ===
def score_1(artifact, step, ctx):
    artifact = artifact  # passed by harness
    step = step

    if not artifact or not isinstance(artifact, dict):
        return 0.0

    target_t_to_h = step.get('T_to_H_target', 0.4)
    target_h_to_v = step.get('H_to_V_target', 0.7)
    tol = step.get('tolerance', 0.05)

    t_to_h = artifact.get('T_to_H')
    h_to_v = artifact.get('H_to_V')

    if t_to_h is None or h_to_v is None:
        return 0.0

    score = 0.0
    if abs(t_to_h - target_t_to_h) <= tol:
        score += 0.5
    if abs(h_to_v - target_h_to_v) <= tol:
        score += 0.5

    return score


_SCORERS = {
    'phase_diagram': score_0,
    'transition_points': score_1,
}


def _step_id(step, index):
    sid = str(step.get("id", "")).strip()
    if sid:
        return sid
    output = str(step.get("output_file", "")).split("/")[-1].rsplit(".", 1)[0]
    kind = str(step.get("kind") or step.get("metric") or "score").strip()
    base = "_".join(part for part in (output, kind) if part).strip("_")
    return base or ("check_" + str(index))


def main():
    _ff_contract_gate()
    with open("/tests/grading_spec.json") as f:
        spec = json.load(f)
    outputs_dir = "/app/outputs"
    ctx = prepare(outputs_dir, spec)
    steps = spec.get("steps", spec.get("checks", [])) or []
    breakdown = {}
    total = 0.0
    for index, step in enumerate(steps):
        sid = _step_id(step, index)
        output_file = str(step.get("output_file", "")).split("/")[-1]
        weight = float(step.get("weight", 0.0))
        artifact = load_artifact(os.path.join(outputs_dir, output_file)) if output_file else None
        fn = _SCORERS.get(sid)
        if fn is None:
            score = 0.0
        else:
            try:
                score = float(fn(artifact, step, ctx))
            except Exception as exc:  # noqa: BLE001
                score = 0.0
                breakdown.setdefault("_errors", {})[sid] = repr(exc)
        score = max(0.0, min(1.0, score))
        breakdown[sid or output_file] = {"score": score, "weight": weight}
        total += score * weight
    os.makedirs("/logs/verifier", exist_ok=True)
    with open("/logs/verifier/reward.txt", "w") as f:
        f.write(str(round(total, 6)))
    with open("/logs/verifier/breakdown.json", "w") as f:
        json.dump(breakdown, f, indent=2)


if __name__ == "__main__":
    main()
