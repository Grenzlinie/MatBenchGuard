# === block: score_0 (check id='transport_results') ===
def score_0(artifact, step, ctx):
    artifact = artifact  # already parsed by the harness
    widths = artifact.get('widths', [])
    temps = artifact.get('temperatures', [])
    on_cond = artifact.get('on_conductance', [])
    peak_mob = artifact.get('peak_mobility', [])
    beta = artifact.get('beta', None)
    width_slope_val = artifact.get('width_slope', None)
    family_ordering = artifact.get('family_ordering', '')

    # build width -> index map
    w_to_idx = {w: i for i, w in enumerate(widths)}
    required_widths = [10, 11, 12]
    if not all(w in w_to_idx for w in required_widths):
        return 0.0

    # locate 300 K column
    if 300 not in temps:
        return 0.0
    t_idx = temps.index(300)

    score = 0.0

    # (a) family ordering exact match
    if family_ordering.strip() == '3j > 3j-1 > 3j+1':
        score += 0.25

    # (b) on_conductance monotonic at 300 K: G_w12 > G_w11 > G_w10
    g10 = on_cond[w_to_idx[10]][t_idx]
    g11 = on_cond[w_to_idx[11]][t_idx]
    g12 = on_cond[w_to_idx[12]][t_idx]
    if g12 > g11 and g11 > g10:
        score += 0.25

    # (c) width_slope positive
    if width_slope_val is not None and width_slope_val > 0:
        score += 0.2

    # (d) beta in (0, 1)
    if beta is not None and 0 < beta < 1:
        score += 0.15

    # (e) peak_mobility monotonic at 300 K
    p10 = peak_mob[w_to_idx[10]][t_idx]
    p11 = peak_mob[w_to_idx[11]][t_idx]
    p12 = peak_mob[w_to_idx[12]][t_idx]
    if p12 > p11 and p11 > p10:
        score += 0.15

    return score


_SCORERS = {
    'transport_results': score_0,
}


def _step_id(step, index):
    sid = str(step.get("id", "")).strip()
    if sid:
        return sid
    output = str(step.get("output_file", "")).split("/")[-1].rsplit(".", 1)[0]
    kind = str(step.get("kind") or step.get("metric") or "score").strip()
    base = "_".join(part for part in (output, kind) if part).strip("_")
    return base or ("check_" + str(index))


def main():
    _ff_contract_gate()
    with open("/tests/grading_spec.json") as f:
        spec = json.load(f)
    outputs_dir = "/app/outputs"
    ctx = prepare(outputs_dir, spec)
    steps = spec.get("steps", spec.get("checks", [])) or []
    breakdown = {}
    total = 0.0
    for index, step in enumerate(steps):
        sid = _step_id(step, index)
        output_file = str(step.get("output_file", "")).split("/")[-1]
        weight = float(step.get("weight", 0.0))
        artifact = load_artifact(os.path.join(outputs_dir, output_file)) if output_file else None
        fn = _SCORERS.get(sid)
        if fn is None:
            score = 0.0
        else:
            try:
                score = float(fn(artifact, step, ctx))
            except Exception as exc:  # noqa: BLE001
                score = 0.0
                breakdown.setdefault("_errors", {})[sid] = repr(exc)
        score = max(0.0, min(1.0, score))
        breakdown[sid or output_file] = {"score": score, "weight": weight}
        total += score * weight
    os.makedirs("/logs/verifier", exist_ok=True)
    with open("/logs/verifier/reward.txt", "w") as f:
        f.write(str(round(total, 6)))
    with open("/logs/verifier/breakdown.json", "w") as f:
        json.dump(breakdown, f, indent=2)


if __name__ == "__main__":
    main()
