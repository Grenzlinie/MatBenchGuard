# === block: score_0 (check id='kappa_values') ===
def score_0(artifact, step, ctx):
    if not isinstance(artifact, list) or len(artifact) < 7:
        return 0.0
    systems_gold = step.get('gold', {})
    tolerance_rel = step.get('tolerance_rel', 0.2)
    # Build dict from artifact
    try:
        art_map = {}
        for row in artifact:
            sys = row.get('system', '').strip()
            k_str = row.get('kappa_300', '')
            if k_str is None or (isinstance(k_str, str) and k_str.strip() == ''):
                art_map[sys] = None
            else:
                art_map[sys] = float(k_str)
        scores = []
        for sys, gold in systems_gold.items():
            art_val = art_map.get(sys)
            if art_val is None:
                scores.append(0.0)
                continue
            if gold == 0:
                scores.append(1.0 if art_val == 0 else 0.0)
            else:
                rel_err = abs(art_val - gold) / gold
                scores.append(1.0 if rel_err <= tolerance_rel else 0.0)
        if not scores:
            return 0.0
        return sum(scores) / len(scores)
    except Exception:
        return 0.0


