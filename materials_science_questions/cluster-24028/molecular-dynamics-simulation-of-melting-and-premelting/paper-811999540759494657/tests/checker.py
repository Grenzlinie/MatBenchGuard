# === block: score_0 (check id='phase_lead_check') ===
def score_0(artifact, step, ctx):
    import csv

    if not isinstance(artifact, list) or len(artifact) != 8:
        return 0.0

    required_cols = {'experiment_id', 'predicted_phase_lead_um'}
    if not required_cols.issubset(artifact[0].keys()):
        return 0.0

    gold = step.get('gold', {})
    coupled = set(step.get('coupled_ids', []))
    noncoupled = set(step.get('noncoupled_ids', []))
    max_abs_diff = step.get('coupled_max_abs_diff', 100)
    min_pred = step.get('noncoupled_min_pred', 200)

    total_score = 0.0
    for row in artifact:
        try:
            exp_id = int(row['experiment_id'])
            pred_val = row.get('predicted_phase_lead_um')
            if pred_val is None:
                pred = None
            else:
                pred = float(pred_val)
        except (ValueError, KeyError, TypeError):
            pred = None

        if pred is None:
            score_contrib = 0.0
        else:
            if exp_id in noncoupled:
                if pred > min_pred:
                    score_contrib = 1.0
                else:
                    score_contrib = 0.0
            elif exp_id in coupled:
                obs_str = gold.get(str(exp_id))
                if obs_str is not None:
                    obs = float(obs_str)
                    if pred <= 0 and abs(pred - obs) <= max_abs_diff:
                        score_contrib = 1.0
                    else:
                        score_contrib = 0.0
                else:
                    score_contrib = 0.0
            else:
                score_contrib = 0.0
        total_score += score_contrib

    return total_score / 8.0


_SCORERS = {
    'phase_lead_check': score_0,
}


def _step_id(step, index):
    sid = str(step.get("id", "")).strip()
    if sid:
        return sid
    output = str(step.get("output_file", "")).split("/")[-1].rsplit(".", 1)[0]
    kind = str(step.get("kind") or step.get("metric") or "score").strip()
    base = "_".join(part for part in (output, kind) if part).strip("_")
    return base or ("check_" + str(index))


def main():
    _ff_contract_gate()
    with open("/tests/grading_spec.json") as f:
        spec = json.load(f)
    outputs_dir = "/app/outputs"
    ctx = prepare(outputs_dir, spec)
    steps = spec.get("steps", spec.get("checks", [])) or []
    breakdown = {}
    total = 0.0
    for index, step in enumerate(steps):
        sid = _step_id(step, index)
        output_file = str(step.get("output_file", "")).split("/")[-1]
        weight = float(step.get("weight", 0.0))
        artifact = load_artifact(os.path.join(outputs_dir, output_file)) if output_file else None
        fn = _SCORERS.get(sid)
        if fn is None:
            score = 0.0
        else:
            try:
                score = float(fn(artifact, step, ctx))
            except Exception as exc:  # noqa: BLE001
                score = 0.0
                breakdown.setdefault("_errors", {})[sid] = repr(exc)
        score = max(0.0, min(1.0, score))
        breakdown[sid or output_file] = {"score": score, "weight": weight}
        total += score * weight
    os.makedirs("/logs/verifier", exist_ok=True)
    with open("/logs/verifier/reward.txt", "w") as f:
        f.write(str(round(total, 6)))
    with open("/logs/verifier/breakdown.json", "w") as f:
        json.dump(breakdown, f, indent=2)


if __name__ == "__main__":
    main()
