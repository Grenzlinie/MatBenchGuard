# === block: score_0 (check id='step_01') ===
def score_0(artifact, step, ctx):
    eps_Si = 0.24
    beta = -0.39
    metals = {'Ni': 5.39, 'Pd': 5.35, 'Pt': 5.08}
    expected = {}
    for m, eps_metal in metals.items():
        V = eps_metal - eps_Si
        term = math.sqrt(4*beta*beta + beta*V + (V*V)/4.0)
        expected[m] = eps_Si + beta + V/2.0 - term

    tolerance = step.get('tolerance_eV', 0.001)
    value_weight = step.get('value_weight', 0.8)
    ordering_weight = step.get('ordering_weight', 0.2)
    expected_ordering = step.get('expected_ordering', ['Pt','Pd','Ni'])

    agent_vals = {}
    for row in artifact:
        metal = row.get('metal', '').strip()
        try:
            val = float(row['defect_level_eV'])
        except (KeyError, ValueError):
            val = None
        if metal in expected:
            agent_vals[metal] = val

    value_match = 0
    for m in expected:
        if m in agent_vals and agent_vals[m] is not None:
            if abs(agent_vals[m] - expected[m]) <= tolerance:
                value_match += 1
    value_score = (value_match / 3) if expected else 0.0

    ordering_correct = False
    ordered_vals = [agent_vals.get(m, None) for m in expected_ordering]
    if all(v is not None for v in ordered_vals):
        if ordered_vals[0] < ordered_vals[1] < ordered_vals[2]:
            ordering_correct = True

    score = value_score * value_weight + (1.0 if ordering_correct else 0.0) * ordering_weight
    return score


_SCORERS = {
    'step_01': score_0,
}


def _step_id(step, index):
    sid = str(step.get("id", "")).strip()
    if sid:
        return sid
    output = str(step.get("output_file", "")).split("/")[-1].rsplit(".", 1)[0]
    kind = str(step.get("kind") or step.get("metric") or "score").strip()
    base = "_".join(part for part in (output, kind) if part).strip("_")
    return base or ("check_" + str(index))


def main():
    _ff_contract_gate()
    with open("/tests/grading_spec.json") as f:
        spec = json.load(f)
    outputs_dir = "/app/outputs"
    ctx = prepare(outputs_dir, spec)
    steps = spec.get("steps", spec.get("checks", [])) or []
    breakdown = {}
    total = 0.0
    for index, step in enumerate(steps):
        sid = _step_id(step, index)
        output_file = str(step.get("output_file", "")).split("/")[-1]
        weight = float(step.get("weight", 0.0))
        artifact = load_artifact(os.path.join(outputs_dir, output_file)) if output_file else None
        fn = _SCORERS.get(sid)
        if fn is None:
            score = 0.0
        else:
            try:
                score = float(fn(artifact, step, ctx))
            except Exception as exc:  # noqa: BLE001
                score = 0.0
                breakdown.setdefault("_errors", {})[sid] = repr(exc)
        score = max(0.0, min(1.0, score))
        breakdown[sid or output_file] = {"score": score, "weight": weight}
        total += score * weight
    os.makedirs("/logs/verifier", exist_ok=True)
    with open("/logs/verifier/reward.txt", "w") as f:
        f.write(str(round(total, 6)))
    with open("/logs/verifier/breakdown.json", "w") as f:
        json.dump(breakdown, f, indent=2)


if __name__ == "__main__":
    main()
