# === block: score_0 (check id='results_json') ===
def score_0(artifact, step, ctx):
    if not isinstance(artifact, dict):
        return 0.0
    strains = ["uni_-2", "uni_-4", "bi_-2", "bi_-6", "bi_-8"]
    gold = step["gold"]
    tolerances = step["tolerances"]

    numeric_fields = [
        ("Bader_charge", 0.05),
        ("interlayer_distance", 0.05),
        ("Re_center", 0.05),
        ("Ox_center", 0.05),
        ("PDS_ph0", 0.1),
        ("EDF_ph0", 0.1),
        ("PDS_ph7", 0.1),
        ("EDF_ph7", 0.1),
        ("m_e/m0", 0.05),
        ("m_h/m0", 0.05),
        ("band_type", 0.1),
        ("feasible_ph0", 0.1),
        ("feasible_ph7", 0.1)
    ]
    total_weight = sum(w for _, w in numeric_fields) * len(strains)
    score = 0.0

    for strain in strains:
        strain_data = artifact.get(strain)
        if not isinstance(strain_data, dict):
            continue
        gold_strain = gold.get(strain, {})
        for field, weight in numeric_fields:
            gold_val = gold_strain.get(field)
            agent_val = strain_data.get(field)
            if gold_val is None:
                continue
            if field in tolerances:
                tol = tolerances[field]
                if isinstance(agent_val, (int, float)) and agent_val is not None:
                    if abs(agent_val - gold_val) <= tol:
                        score += weight
            elif field in ("band_type",):
                if agent_val in ("Z-scheme", "type-II") and agent_val == gold_val:
                    score += weight
            elif field in ("feasible_ph0", "feasible_ph7"):
                if agent_val == gold_val:
                    score += weight
    return score / total_weight if total_weight > 0 else 0.0


_SCORERS = {
    'results_json': score_0,
}


def _step_id(step, index):
    sid = str(step.get("id", "")).strip()
    if sid:
        return sid
    output = str(step.get("output_file", "")).split("/")[-1].rsplit(".", 1)[0]
    kind = str(step.get("kind") or step.get("metric") or "score").strip()
    base = "_".join(part for part in (output, kind) if part).strip("_")
    return base or ("check_" + str(index))


def main():
    _ff_contract_gate()
    with open("/tests/grading_spec.json") as f:
        spec = json.load(f)
    outputs_dir = "/app/outputs"
    ctx = prepare(outputs_dir, spec)
    steps = spec.get("steps", spec.get("checks", [])) or []
    breakdown = {}
    total = 0.0
    for index, step in enumerate(steps):
        sid = _step_id(step, index)
        output_file = str(step.get("output_file", "")).split("/")[-1]
        weight = float(step.get("weight", 0.0))
        artifact = load_artifact(os.path.join(outputs_dir, output_file)) if output_file else None
        fn = _SCORERS.get(sid)
        if fn is None:
            score = 0.0
        else:
            try:
                score = float(fn(artifact, step, ctx))
            except Exception as exc:  # noqa: BLE001
                score = 0.0
                breakdown.setdefault("_errors", {})[sid] = repr(exc)
        score = max(0.0, min(1.0, score))
        breakdown[sid or output_file] = {"score": score, "weight": weight}
        total += score * weight
    os.makedirs("/logs/verifier", exist_ok=True)
    with open("/logs/verifier/reward.txt", "w") as f:
        f.write(str(round(total, 6)))
    with open("/logs/verifier/breakdown.json", "w") as f:
        json.dump(breakdown, f, indent=2)


if __name__ == "__main__":
    main()
