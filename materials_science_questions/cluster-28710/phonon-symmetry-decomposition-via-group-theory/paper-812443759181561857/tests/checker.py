# === block: score_0 (check id='phonon_analysis') ===
def score_0(artifact, step, ctx):
    import re
    artifact = artifact
    step = step
    gold = step.get('gold', {})

    def normalize_irrep_set(irrep_arr):
        if not isinstance(irrep_arr, list):
            return None
        normalized = []
        for s in irrep_arr:
            if isinstance(s, str):
                normalized.append(re.sub(r'[^A-Za-z0-9_]', '', s.strip()))
        return sorted(normalized)

    gamma_modes = artifact.get('gamma_modes', {})
    m_modes = artifact.get('M_modes', {})
    gamma_Zr = normalize_irrep_set(gamma_modes.get('Zr', []))
    gamma_O = normalize_irrep_set(gamma_modes.get('O', []))
    M_Zr = normalize_irrep_set(m_modes.get('Zr', []))
    M_O = normalize_irrep_set(m_modes.get('O', []))

    gold_gamma_Zr = sorted(gold.get('gamma_Zr', []))
    gold_gamma_O = sorted(gold.get('gamma_O', []))
    gold_M_Zr = sorted(gold.get('M_Zr', []))
    gold_M_O = sorted(gold.get('M_O', []))

    score_gamma = 1.0 if gamma_Zr == gold_gamma_Zr and gamma_O == gold_gamma_O else 0.0
    score_M = 1.0 if M_Zr == gold_M_Zr and M_O == gold_M_O else 0.0

    pri_param = artifact.get('primary_order_parameter', '')
    score_primary = 1.0 if pri_param == gold['primary_order_parameter'] else 0.0

    coupling_terms = artifact.get('coupling_terms', [])
    shear_found = False
    for term in coupling_terms:
        if isinstance(term, str) and 'e4' in term and 'e5' in term and ('φ' in term or 'ψ' in term):
            shear_found = True
            break
    score_coupling = 1.0 if shear_found else 0.0

    total = 0.25 * score_gamma + 0.25 * score_M + 0.25 * score_primary + 0.25 * score_coupling
    return total


_SCORERS = {
    'phonon_analysis': score_0,
}


def _step_id(step, index):
    sid = str(step.get("id", "")).strip()
    if sid:
        return sid
    output = str(step.get("output_file", "")).split("/")[-1].rsplit(".", 1)[0]
    kind = str(step.get("kind") or step.get("metric") or "score").strip()
    base = "_".join(part for part in (output, kind) if part).strip("_")
    return base or ("check_" + str(index))


def main():
    _ff_contract_gate()
    with open("/tests/grading_spec.json") as f:
        spec = json.load(f)
    outputs_dir = "/app/outputs"
    ctx = prepare(outputs_dir, spec)
    steps = spec.get("steps", spec.get("checks", [])) or []
    breakdown = {}
    total = 0.0
    for index, step in enumerate(steps):
        sid = _step_id(step, index)
        output_file = str(step.get("output_file", "")).split("/")[-1]
        weight = float(step.get("weight", 0.0))
        artifact = load_artifact(os.path.join(outputs_dir, output_file)) if output_file else None
        fn = _SCORERS.get(sid)
        if fn is None:
            score = 0.0
        else:
            try:
                score = float(fn(artifact, step, ctx))
            except Exception as exc:  # noqa: BLE001
                score = 0.0
                breakdown.setdefault("_errors", {})[sid] = repr(exc)
        score = max(0.0, min(1.0, score))
        breakdown[sid or output_file] = {"score": score, "weight": weight}
        total += score * weight
    os.makedirs("/logs/verifier", exist_ok=True)
    with open("/logs/verifier/reward.txt", "w") as f:
        f.write(str(round(total, 6)))
    with open("/logs/verifier/breakdown.json", "w") as f:
        json.dump(breakdown, f, indent=2)


if __name__ == "__main__":
    main()
