def score_0(artifact, step, ctx):
    if artifact is None or not isinstance(artifact, list) or len(artifact) == 0:
        return 0.0
    required_cols = {'atom', 'eta', 'lambda'}
    if not required_cols.issubset(artifact[0].keys()):
        return 0.0
    gold = step.get('gold', {})
    tols = step.get('tolerances', {})
    rel_tol = float(tols.get('relative', 0.1))
    abs_tol = float(tols.get('absolute', 0.02))
    def in_tol(actual, target):
        if target > 0.1:
            if target == 0:
                return abs(actual) <= abs_tol
            return abs(actual - target) <= rel_tol * abs(target)
        else:
            return abs(actual - target) <= abs_tol
    rows_by_atom = {}
    for row in artifact:
        atom = str(row.get('atom', '')).strip().lower()
        rows_by_atom[atom] = row
    checks = []
    for atom_key in ['li', 'pd', 'h', 'total']:
        row = rows_by_atom.get(atom_key, None)
        if row is None:
            checks.extend([False, False] if atom_key != 'total' else [False])
            continue
        if atom_key == 'total':
            try:
                lam = float(row.get('lambda', math.nan))
            except (ValueError, TypeError):
                lam = math.nan
            checks.append(not math.isnan(lam) and in_tol(lam, gold['total_lambda']))
        else:
            try:
                eta_val = float(row.get('eta', math.nan))
                lam_val = float(row.get('lambda', math.nan))
            except (ValueError, TypeError):
                eta_val = math.nan
                lam_val = math.nan
            checks.append(not math.isnan(eta_val) and in_tol(eta_val, gold[f'{atom_key}_eta']))
            checks.append(not math.isnan(lam_val) and in_tol(lam_val, gold[f'{atom_key}_lambda']))
    if len(checks) == 0:
        return 0.0
    return sum(checks) / len(checks)


_SCORERS = {
    'rmta_metrics_check': score_0,
}


def _step_id(step, index):
    sid = str(step.get("id", "")).strip()
    if sid:
        return sid
    output = str(step.get("output_file", "")).split("/")[-1].rsplit(".", 1)[0]
    kind = str(step.get("kind") or step.get("metric") or "score").strip()
    base = "_".join(part for part in (output, kind) if part).strip("_")
    return base or ("check_" + str(index))


def main():
    _ff_contract_gate()
    with open("/tests/grading_spec.json") as f:
        spec = json.load(f)
    outputs_dir = "/app/outputs"
    ctx = prepare(outputs_dir, spec)
    steps = spec.get("steps", spec.get("checks", [])) or []
    breakdown = {}
    total = 0.0
    for index, step in enumerate(steps):
        sid = _step_id(step, index)
        output_file = str(step.get("output_file", "")).split("/")[-1]
        weight = float(step.get("weight", 0.0))
        artifact = load_artifact(os.path.join(outputs_dir, output_file)) if output_file else None
        fn = _SCORERS.get(sid)
        if fn is None:
            score = 0.0
        else:
            try:
                score = float(fn(artifact, step, ctx))
            except Exception as exc:  # noqa: BLE001
                score = 0.0
                breakdown.setdefault("_errors", {})[sid] = repr(exc)
        score = max(0.0, min(1.0, score))
        breakdown[sid or output_file] = {"score": score, "weight": weight}
        total += score * weight
    os.makedirs("/logs/verifier", exist_ok=True)
    with open("/logs/verifier/reward.txt", "w") as f:
        f.write(str(round(total, 6)))
    with open("/logs/verifier/breakdown.json", "w") as f:
        json.dump(breakdown, f, indent=2)


if __name__ == "__main__":
    main()
