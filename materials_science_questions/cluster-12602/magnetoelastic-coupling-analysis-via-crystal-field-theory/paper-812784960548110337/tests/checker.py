def score_0(artifact, step, ctx):
    def pearsonr(x, y):
        n = len(x)
        if n < 2:
            return 0.0
        mean_x = sum(x) / n
        mean_y = sum(y) / n
        num = sum((xi - mean_x) * (yi - mean_y) for xi, yi in zip(x, y))
        denom = math.sqrt(sum((xi - mean_x)**2 for xi in x) * sum((yi - mean_y)**2 for yi in y))
        if denom == 0:
            return 0.0
        return num / denom

    expected_affected = {
        'Ag1': {'xxxz', 'yyyz'},
        'Ag2': {'zzzz'},
        'Ag3': {'xxxz', 'xxyy', 'xzzz', 'yxxx', 'yyyz', 'zzxx', 'zzxy', 'zzzz'},
        'Ag4': {'xxxz', 'xxyy', 'xzzz', 'yxxx', 'yyyz', 'zzxx', 'zzxy', 'zzzz'},
    }

    rows = artifact
    mode_scores = []
    for mode in ['Ag1', 'Ag2', 'Ag3', 'Ag4']:
        mode_rows = [r for r in rows if r.get('distortion_type') == mode]
        if not mode_rows:
            mode_scores.append(0.0)
            continue
        expected_set = expected_affected.get(mode, set())
        x_agent = []
        x_expected = []
        for r in mode_rows:
            try:
                delta = float(r['delta'])
                delta_chi = float(r['delta_chi'])
            except (ValueError, KeyError):
                continue
            elem = r.get('tensor_element', '')
            expected_val = delta if elem in expected_set else 0.0
            x_agent.append(delta_chi)
            x_expected.append(expected_val)
        if len(x_agent) < 2:
            mode_scores.append(0.0)
            continue
        r_val = pearsonr(x_agent, x_expected)
        if math.isnan(r_val):
            r_val = 0.0
        score = max(0.0, min(1.0, r_val))
        mode_scores.append(score)

    if mode_scores:
        final_score = sum(mode_scores) / len(mode_scores)
    else:
        final_score = 0.0
    return final_score


_SCORERS = {
    'bond_model_verify': score_0,
}


def _step_id(step, index):
    sid = str(step.get("id", "")).strip()
    if sid:
        return sid
    output = str(step.get("output_file", "")).split("/")[-1].rsplit(".", 1)[0]
    kind = str(step.get("kind") or step.get("metric") or "score").strip()
    base = "_".join(part for part in (output, kind) if part).strip("_")
    return base or ("check_" + str(index))


def main():
    _ff_contract_gate()
    with open("/tests/grading_spec.json") as f:
        spec = json.load(f)
    outputs_dir = "/app/outputs"
    ctx = prepare(outputs_dir, spec)
    steps = spec.get("steps", spec.get("checks", [])) or []
    breakdown = {}
    total = 0.0
    for index, step in enumerate(steps):
        sid = _step_id(step, index)
        output_file = str(step.get("output_file", "")).split("/")[-1]
        weight = float(step.get("weight", 0.0))
        artifact = load_artifact(os.path.join(outputs_dir, output_file)) if output_file else None
        fn = _SCORERS.get(sid)
        if fn is None:
            score = 0.0
        else:
            try:
                score = float(fn(artifact, step, ctx))
            except Exception as exc:  # noqa: BLE001
                score = 0.0
                breakdown.setdefault("_errors", {})[sid] = repr(exc)
        score = max(0.0, min(1.0, score))
        breakdown[sid or output_file] = {"score": score, "weight": weight}
        total += score * weight
    os.makedirs("/logs/verifier", exist_ok=True)
    with open("/logs/verifier/reward.txt", "w") as f:
        f.write(str(round(total, 6)))
    with open("/logs/verifier/breakdown.json", "w") as f:
        json.dump(breakdown, f, indent=2)


if __name__ == "__main__":
    main()
