def score_0(artifact, step, ctx):
    try:
        k_points = artifact['k_points']
        eigenvalues = artifact['eigenvalues']
        fermi = artifact.get('fermi_energy', 0.0)
        gamma_idx = None
        m_idx = None
        for i, kp in enumerate(k_points):
            if kp.get('label') == 'Gamma':
                gamma_idx = i
            elif kp.get('label') == 'M':
                m_idx = i
        if gamma_idx is None or m_idx is None:
            return 0.0
        eig_g = [band[gamma_idx] for band in eigenvalues]
        eig_m = [band[m_idx] for band in eigenvalues]
        # Valence band maximum (<= Fermi) and conduction band minimum (> Fermi) at Gamma
        vbm_g = max(e for e in eig_g if e <= fermi + 1e-9)
        cbm_g = min(e for e in eig_g if e > fermi + 1e-9)
        gap = cbm_g - vbm_g
        # Conduction band minimum at M
        cbm_m = min(e for e in eig_m if e > fermi + 1e-9)
        delta = abs(cbm_g - cbm_m)
        gap_min, gap_max = step['gap_range']
        delta_max = step['delta_max']
        # Score gap: full within range, otherwise linear decay
        if gap >= gap_min and gap <= gap_max:
            s_gap = 1.0
        elif gap < gap_min:
            s_gap = max(0.0, 1.0 - (gap_min - gap) / 0.1)
        else:
            s_gap = max(0.0, 1.0 - (gap - gap_max) / 0.1)
        # Score delta: full if <= delta_max, otherwise linear decay
        if delta <= delta_max:
            s_delta = 1.0
        else:
            s_delta = max(0.0, 1.0 - (delta - delta_max) / 0.01)
        return (s_gap + s_delta) / 2.0
    except Exception:
        return 0.0


