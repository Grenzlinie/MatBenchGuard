# === block: score_0 (check id='dipole_compare') ===
def score_0(artifact, step, ctx):
    # Build groups from gold_rows to handle duplicates with identical (table_type, form, configuration, pairs_count)
    groups = {}
    for gr in step.get("gold_rows", []):
        key = (gr[0], gr[1], gr[2], int(gr[3]))
        dipole = float(gr[4])
        groups.setdefault(key, []).append(dipole)

    tolerance = step.get("tolerance", 0.03)

    # Parse agent rows
    agent = []
    for row in artifact:
        dipole_val = row.get("dipole_moment_D")
        pairs_val = row.get("pairs_count")
        if dipole_val is None or pairs_val is None:
            continue
        try:
            dipole = float(dipole_val)
            pairs = int(pairs_val)
        except (ValueError, TypeError):
            continue
        agent.append((row.get("table_type","").strip(), row.get("form","").strip(), row.get("configuration","").strip(), pairs, dipole))

    # Greedy match one agent row per group
    used = [False]*len(agent)
    matched_groups = 0
    for key, gold_dipoles in groups.items():
        t, f, cfg, gp = key
        found = False
        for i, ar in enumerate(agent):
            if used[i]: continue
            if ar[0]==t and ar[1]==f and ar[2]==cfg and ar[3]==gp:
                if any(abs(ar[4]-gd) <= tolerance for gd in gold_dipoles):
                    used[i]=True ; matched_groups+=1 ; found=True ; break

    total = len(groups)
    score = matched_groups / max(total, 1)
    return score


_SCORERS = {
    'dipole_compare': score_0,
}


def _step_id(step, index):
    sid = str(step.get("id", "")).strip()
    if sid:
        return sid
    output = str(step.get("output_file", "")).split("/")[-1].rsplit(".", 1)[0]
    kind = str(step.get("kind") or step.get("metric") or "score").strip()
    base = "_".join(part for part in (output, kind) if part).strip("_")
    return base or ("check_" + str(index))


def main():
    _ff_contract_gate()
    with open("/tests/grading_spec.json") as f:
        spec = json.load(f)
    outputs_dir = "/app/outputs"
    ctx = prepare(outputs_dir, spec)
    steps = spec.get("steps", spec.get("checks", [])) or []
    breakdown = {}
    total = 0.0
    for index, step in enumerate(steps):
        sid = _step_id(step, index)
        output_file = str(step.get("output_file", "")).split("/")[-1]
        weight = float(step.get("weight", 0.0))
        artifact = load_artifact(os.path.join(outputs_dir, output_file)) if output_file else None
        fn = _SCORERS.get(sid)
        if fn is None:
            score = 0.0
        else:
            try:
                score = float(fn(artifact, step, ctx))
            except Exception as exc:  # noqa: BLE001
                score = 0.0
                breakdown.setdefault("_errors", {})[sid] = repr(exc)
        score = max(0.0, min(1.0, score))
        breakdown[sid or output_file] = {"score": score, "weight": weight}
        total += score * weight
    os.makedirs("/logs/verifier", exist_ok=True)
    with open("/logs/verifier/reward.txt", "w") as f:
        f.write(str(round(total, 6)))
    with open("/logs/verifier/breakdown.json", "w") as f:
        json.dump(breakdown, f, indent=2)


if __name__ == "__main__":
    main()
