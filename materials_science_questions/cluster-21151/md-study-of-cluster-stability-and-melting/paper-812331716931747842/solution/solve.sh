import csv
E_min = -642.5
E_max = -625.1
start = -643.0
step = 0.5
n = 39
data = []
for i in range(n):
    e = start + i*step
    y = (e - E_min)/(E_max - E_min)
    if y < 0: y = 0
    elif y > 1: y = 1
    data.append((e, y))
with open('/app/outputs/kcl_5832_liq_mol_frac.csv', 'w', newline='') as f:
