# === block: score_0 (check id='results_check') ===
def score_0(artifact, step, ctx):
    cfg = step.get('config', {})
    target_energy = cfg['target_energy_keV']
    ts_lo = cfg['ts_lo']
    ts_hi = cfg['ts_hi']
    nsec_lo = cfg['nsec_lo']
    nsec_hi = cfg['nsec_hi']
    subw = cfg['sub_weights']
    energies_mono = cfg['monotonic_energies']

    # artifact is a list of dicts (loaded csv)
    rows = artifact
    data = {}
    for row in rows:
        try:
            e = float(row['energy_keV'])
            ts = float(row['storage_time_hours'])
            ns = int(row['secondary_count'])
            if e not in data:
                data[e] = {'ts': ts, 'ns': ns}
        except (ValueError, KeyError):
            continue

    # 10 keV point
    score_ts = 0
    score_ns = 0
    if target_energy in data:
        d = data[target_energy]
        if ts_lo <= d['ts'] <= ts_hi:
            score_ts = 1.0
        if nsec_lo <= d['ns'] <= nsec_hi:
            score_ns = 1.0

    # monotonic trend
    mono_ts = True
    mono_ns = True
    prev_ts = -1
    prev_ns = -1
    for e in sorted(energies_mono):
        if e in data:
            cur_ts = data[e]['ts']
            cur_ns = data[e]['ns']
            if cur_ts < prev_ts:
                mono_ts = False
            if cur_ns < prev_ns:
                mono_ns = False
            prev_ts = cur_ts
            prev_ns = cur_ns
        else:
            mono_ts = False
            mono_ns = False
    monotonic_score = 1.0 if (mono_ts and mono_ns) else 0.0

    total = subw['ts_10keV'] * score_ts + subw['nsec_10keV'] * score_ns + subw['monotonic'] * monotonic_score
    return total


_SCORERS = {
    'results_check': score_0,
}


def _step_id(step, index):
    sid = str(step.get("id", "")).strip()
    if sid:
        return sid
    output = str(step.get("output_file", "")).split("/")[-1].rsplit(".", 1)[0]
    kind = str(step.get("kind") or step.get("metric") or "score").strip()
    base = "_".join(part for part in (output, kind) if part).strip("_")
    return base or ("check_" + str(index))


def main():
    _ff_contract_gate()
    with open("/tests/grading_spec.json") as f:
        spec = json.load(f)
    outputs_dir = "/app/outputs"
    ctx = prepare(outputs_dir, spec)
    steps = spec.get("steps", spec.get("checks", [])) or []
    breakdown = {}
    total = 0.0
    for index, step in enumerate(steps):
        sid = _step_id(step, index)
        output_file = str(step.get("output_file", "")).split("/")[-1]
        weight = float(step.get("weight", 0.0))
        artifact = load_artifact(os.path.join(outputs_dir, output_file)) if output_file else None
        fn = _SCORERS.get(sid)
        if fn is None:
            score = 0.0
        else:
            try:
                score = float(fn(artifact, step, ctx))
            except Exception as exc:  # noqa: BLE001
                score = 0.0
                breakdown.setdefault("_errors", {})[sid] = repr(exc)
        score = max(0.0, min(1.0, score))
        breakdown[sid or output_file] = {"score": score, "weight": weight}
        total += score * weight
    os.makedirs("/logs/verifier", exist_ok=True)
    with open("/logs/verifier/reward.txt", "w") as f:
        f.write(str(round(total, 6)))
    with open("/logs/verifier/breakdown.json", "w") as f:
        json.dump(breakdown, f, indent=2)


if __name__ == "__main__":
    main()
